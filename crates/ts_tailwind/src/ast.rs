//! Tailwind's intermediate CSS tree. Derived from Tailwind CSS v4.2.1 (MIT).
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

/// Source offsets are UTF-8 byte offsets, never JavaScript UTF-16 offsets.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SourceLocation {
    pub file: String,
    pub start: usize,
    pub end: usize,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum ContextValue {
    String(String),
    Bool(bool),
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AstNode {
    #[serde(flatten)]
    pub kind: NodeKind,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub src: Option<SourceLocation>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub dst: Option<SourceLocation>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "kebab-case")]
pub enum NodeKind {
    Rule {
        selector: String,
        nodes: Vec<AstNode>,
    },
    AtRule {
        name: String,
        params: String,
        nodes: Vec<AstNode>,
    },
    Declaration {
        property: String,
        value: Option<String>,
        important: bool,
    },
    Comment {
        value: String,
    },
    Context {
        context: BTreeMap<String, ContextValue>,
        nodes: Vec<AstNode>,
    },
    AtRoot {
        nodes: Vec<AstNode>,
    },
}

impl AstNode {
    pub fn new(kind: NodeKind) -> Self {
        Self {
            kind,
            src: None,
            dst: None,
        }
    }
    pub fn declaration(property: impl Into<String>, value: impl Into<String>) -> Self {
        Self::new(NodeKind::Declaration {
            property: property.into(),
            value: Some(value.into()),
            important: false,
        })
    }
    pub fn children(&self) -> Option<&[AstNode]> {
        match &self.kind {
            NodeKind::Rule { nodes, .. }
            | NodeKind::AtRule { nodes, .. }
            | NodeKind::Context { nodes, .. }
            | NodeKind::AtRoot { nodes } => Some(nodes),
            _ => None,
        }
    }
    pub fn children_mut(&mut self) -> Option<&mut Vec<AstNode>> {
        match &mut self.kind {
            NodeKind::Rule { nodes, .. }
            | NodeKind::AtRule { nodes, .. }
            | NodeKind::Context { nodes, .. }
            | NodeKind::AtRoot { nodes } => Some(nodes),
            _ => None,
        }
    }
}

/// Print a finalized tree, recording exact generated byte ranges. Compiler-only
/// context/at-root nodes and absent declaration values must be lowered first.
pub fn to_css(ast: &mut [AstNode], file: &str) -> Result<String, String> {
    fn emit(ast: &mut [AstNode], file: &str, depth: usize, out: &mut String) -> Result<(), String> {
        if depth > 256 {
            return Err("CSS printing nesting limit exceeded".into());
        }
        for node in ast {
            let indent = "  ".repeat(depth);
            out.push_str(&indent);
            let start = out.len();
            let (end, children) = match &mut node.kind {
                NodeKind::Declaration {
                    property,
                    value,
                    important,
                } => {
                    let value = value
                        .as_ref()
                        .ok_or("Cannot print an unresolved declaration value")?;
                    out.push_str(property);
                    out.push_str(": ");
                    out.push_str(value);
                    if *important {
                        out.push_str(" !important");
                    }
                    let end = out.len();
                    out.push_str(";\n");
                    (end, None)
                }
                NodeKind::Comment { value } => {
                    out.push_str("/*");
                    out.push_str(value);
                    out.push_str("*/\n");
                    (out.len() - 1, None)
                }
                NodeKind::Rule { selector, nodes } => {
                    out.push_str(selector);
                    out.push(' ');
                    let end = out.len();
                    out.push_str("{\n");
                    (end, Some(nodes))
                }
                NodeKind::AtRule {
                    name,
                    params,
                    nodes,
                } => {
                    out.push_str(name);
                    out.push(' ');
                    out.push_str(params);
                    if nodes.is_empty() {
                        let end = out.len();
                        out.push_str(";\n");
                        (end, None)
                    } else {
                        if !params.is_empty() {
                            out.push(' ');
                        }
                        let end = out.len();
                        out.push_str("{\n");
                        (end, Some(nodes))
                    }
                }
                NodeKind::Context { .. } | NodeKind::AtRoot { .. } => {
                    return Err(
                        "Compiler context/at-root nodes must be lowered before printing".into(),
                    );
                }
            };
            if let Some(children) = children {
                emit(children, file, depth + 1, out)?;
                out.push_str(&indent);
                out.push_str("}\n");
            }
            node.dst = Some(SourceLocation {
                file: file.into(),
                start,
                end,
            });
        }
        Ok(())
    }
    let mut out = String::new();
    emit(ast, file, 0, &mut out)?;
    Ok(out)
}
