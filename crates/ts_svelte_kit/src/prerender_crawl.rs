#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum CrawlProfile {
    #[serde(rename = "2.69.2")]
    Kit2_69_2,
    #[serde(rename = "3.0.1")]
    Kit3_0_1,
}

#[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
pub struct CrawlResult {
    pub ids: Vec<String>,
    pub hrefs: Vec<String>,
    pub invalid: Vec<String>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum CrawlErrorKind {
    Limit,
    InvalidUrl,
    InvalidUri,
    UnsupportedUtf16,
    UpstreamNonTermination,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub struct CrawlError {
    pub kind: CrawlErrorKind,
    pub message: String,
}
impl std::fmt::Display for CrawlError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.message)
    }
}
impl std::error::Error for CrawlError {}
fn error(kind: CrawlErrorKind, message: impl Into<String>) -> CrawlError {
    CrawlError {
        kind,
        message: message.into(),
    }
}

/// Limits bound input, aggregate returned strings, and result count. Reaching a
/// limit fails the whole operation; no partially scanned result is returned.
#[derive(Clone, Copy, Debug)]
pub struct CrawlLimits {
    pub html_bytes: usize,
    pub result_bytes: usize,
    pub results: usize,
}
impl Default for CrawlLimits {
    fn default() -> Self {
        Self {
            html_bytes: 16 * 1024 * 1024,
            result_bytes: 64 * 1024 * 1024,
            results: 100_000,
        }
    }
}

/// Kit's URL helper. Protocol-relative references return verbatim, even when a
/// URL parser would reject them. The internal scheme differs between families.
pub fn resolve_link(base: &str, path: &str, profile: CrawlProfile) -> Result<String, CrawlError> {
    if path.starts_with("//") {
        return Ok(path.to_owned());
    }
    let scheme = match profile {
        CrawlProfile::Kit2_69_2 => "sveltekit-internal",
        CrawlProfile::Kit3_0_1 => "a",
    };
    let internal = Url::parse(&format!("{scheme}://")).expect("constant hierarchical URL");
    let resolved = internal
        .join(base)
        .and_then(|base| base.join(path))
        .map_err(|e| {
            error(
                CrawlErrorKind::InvalidUrl,
                format!("Invalid URL reference {path:?} against {base:?}: {e}"),
            )
        })?;
    if resolved.scheme() == scheme {
        // URL.search and URL.hash omit empty delimiters, unlike URL.href.
        let mut result = resolved.path().to_owned();
        if let Some(query) = resolved.query().filter(|v| !v.is_empty()) {
            result.push('?');
            result.push_str(query);
        }
        if let Some(hash) = resolved.fragment().filter(|v| !v.is_empty()) {
            result.push('#');
            result.push_str(hash);
        }
        Ok(result)
    } else {
        Ok(resolved.to_string())
    }
}

/// JavaScript decodeURI, retaining the original escape spelling for reserved
/// delimiters. Invalid UTF-8, surrogate encodings and incomplete escapes fail.
pub fn decode_uri(value: &str) -> Result<String, CrawlError> {
    let bytes = value.as_bytes();
    let invalid = || {
        error(
            CrawlErrorKind::InvalidUri,
            format!("Failed to decode URI: {value}\nURI malformed"),
        )
    };
    let mut output = String::with_capacity(value.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] != b'%' {
            let c = value[i..].chars().next().unwrap();
            output.push(c);
            i += c.len_utf8();
            continue;
        }
        let start = i;
        let first = percent(bytes, i).ok_or_else(invalid)?;
        let count = match first {
            0..=0x7f => 1,
            0xc2..=0xdf => 2,
            0xe0..=0xef => 3,
            0xf0..=0xf4 => 4,
            _ => return Err(invalid()),
        };
        let mut scalar = [0; 4];
        scalar[0] = first;
        i += 3;
        for slot in scalar.iter_mut().take(count).skip(1) {
            *slot = percent(bytes, i).ok_or_else(invalid)?;
            i += 3;
        }
        let decoded = std::str::from_utf8(&scalar[..count]).map_err(|_| invalid())?;
        if count == 1 && b";/?:@&=+$,#".contains(&first) {
            output.push_str(&value[start..i]);
        } else {
            output.push_str(decoded);
        }
    }
    Ok(output)
}
fn percent(bytes: &[u8], i: usize) -> Option<u8> {
    if bytes.get(i) != Some(&b'%') {
        return None;
    }
    let high = (*bytes.get(i + 1)? as char).to_digit(16)?;
    let low = (*bytes.get(i + 2)? as char).to_digit(16)?;
    Some((high * 16 + low) as u8)
}

// ECMAScript WhiteSpace + LineTerminator (not Rust's Unicode whitespace set).
fn whitespace(c: char) -> bool {
    matches!(c, '\u{9}'..='\u{d}' | ' ' | '\u{a0}' | '\u{1680}' | '\u{2000}'..='\u{200a}' | '\u{2028}' | '\u{2029}' | '\u{202f}' | '\u{205f}' | '\u{3000}' | '\u{feff}')
}
fn attribute_name(c: char) -> bool {
    !matches!(
        c,
        '\t' | '\n' | '\u{c}' | ' ' | '/' | '>' | '"' | '\'' | '='
    )
}
fn slice(chars: &[char], start: usize, end: usize) -> String {
    chars[start.min(chars.len())..end.min(chars.len())]
        .iter()
        .collect()
}
fn starts(chars: &[char], i: usize, pattern: &str, insensitive: bool) -> bool {
    if !insensitive {
        return pattern
            .chars()
            .enumerate()
            .all(|(n, p)| chars.get(i + n) == Some(&p));
    }
    // Upstream slices by UTF16 code units before Unicode toUpperCase, so e.g.
    // a long-s in </ſcript> closes raw text, but expansion cannot extend the slice.
    let mut units = 0;
    let mut end = i;
    while let Some(c) = chars.get(end) {
        units += c.len_utf16();
        if units > pattern.len() {
            return false;
        }
        end += 1;
        if units == pattern.len() {
            return slice(chars, i, end).to_uppercase() == pattern;
        }
    }
    false
}
fn external(rel: &str) -> bool {
    let word = |b: u8| b.is_ascii_alphanumeric() || b == b'_';
    rel.as_bytes().windows(8).enumerate().any(|(i, v)| {
        v.eq_ignore_ascii_case(b"external")
            && (i == 0 || !word(rel.as_bytes()[i - 1]))
            && (i + 8 == rel.len() || !word(rel.as_bytes()[i + 8]))
    })
}
fn meta(name: &str) -> bool {
    matches!(
        name,
        "og:url"
            | "og:image"
            | "og:image:url"
            | "og:image:secure_url"
            | "og:video"
            | "og:video:url"
            | "og:video:secure_url"
            | "og:audio"
            | "og:audio:url"
            | "og:audio:secure_url"
            | "twitter:image"
    )
}

/// Decode exactly Kit's numeric-then-named references, not an HTML5 parser's
/// attribute entity algorithm. Kit2 replaces only the first numeric reference.
/// UTF16 pairs are retained until both passes finish; unpaired surrogates are an
/// explicit unsupported boundary because Rust/JSON string APIs require UTF8.
pub fn decode_entities(value: &str, profile: CrawlProfile) -> Result<String, CrawlError> {
    let bytes = value.as_bytes();
    let mut units = Vec::new();
    let mut copied = 0;
    let mut i = 0;
    while i + 3 < bytes.len() {
        if bytes[i] != b'&' || bytes[i + 1] != b'#' {
            i += 1;
            continue;
        }
        let mut end = i + 2;
        let hex = matches!(bytes.get(end), Some(b'x' | b'X'));
        if hex {
            end += 1;
        }
        let begin = end;
        while bytes.get(end).is_some_and(u8::is_ascii_hexdigit) {
            end += 1;
        }
        if end == begin || bytes.get(end) != Some(&b';') {
            i += 1;
            continue;
        }
        units.extend(value[copied..i].encode_utf16());
        let number = if hex {
            // Values beyond 128 bits exceed the Unicode range, and their IEEE
            // integer representation has zero low 16 bits (Kit2 ToUint16).
            u128::from_str_radix(&value[begin..end].trim_start_matches('0'), 16)
                .map(|v| v as f64)
                .unwrap_or_else(|_| {
                    if bytes[begin..end].iter().all(|b| *b == b'0') {
                        0.0
                    } else {
                        f64::INFINITY
                    }
                })
        } else {
            let code = &value[begin..end];
            if code.starts_with("0b") || code.starts_with("0B") {
                let digits = &code[2..];
                if !digits.is_empty() && digits.bytes().all(|b| b == b'0' || b == b'1') {
                    u128::from_str_radix(digits.trim_start_matches('0'), 2)
                        .map(|v| v as f64)
                        .unwrap_or_else(|_| {
                            if digits.bytes().all(|b| b == b'0') {
                                0.0
                            } else {
                                f64::INFINITY
                            }
                        })
                } else {
                    f64::NAN
                }
            } else {
                code.parse::<f64>().unwrap_or(f64::NAN)
            }
        };
        match profile {
            CrawlProfile::Kit2_69_2 => units.push(if number.is_finite() {
                number.trunc().rem_euclid(65536.0) as u16
            } else {
                0
            }),
            CrawlProfile::Kit3_0_1 => {
                let code = if number.is_finite()
                    && number.fract() == 0.0
                    && (0.0..=0x10ffff as f64).contains(&number)
                {
                    number as u32
                } else {
                    0xfffd
                };
                if code <= 0xffff {
                    units.push(code as u16);
                } else {
                    let n = code - 0x10000;
                    units.push(0xd800 + (n >> 10) as u16);
                    units.push(0xdc00 + (n & 1023) as u16);
                }
            }
        }
        copied = end + 1;
        i = copied;
        if profile == CrawlProfile::Kit2_69_2 {
            break;
        }
    }
    units.extend(value[copied..].encode_utf16());
    let mut output = Vec::with_capacity(units.len());
    let mut i = 0;
    while i < units.len() {
        if units[i] == b'&' as u16 {
            let mut key = String::new();
            let mut found = None;
            for end in i + 1..units.len().min(i + 33) {
                let unit = units[end];
                if unit > 127 {
                    break;
                }
                key.push(unit as u8 as char);
                if let Ok(index) = ENTITIES.binary_search_by_key(&key.as_str(), |(name, _)| *name) {
                    found = Some((end + 1, ENTITIES[index].1));
                }
            }
            if let Some((end, value)) = found {
                output.extend(value.encode_utf16());
                i = end;
                continue;
            }
        }
        output.push(units[i]);
        i += 1;
    }
    String::from_utf16(&output).map_err(|_| error(CrawlErrorKind::UnsupportedUtf16, "HTML entity decoding produced an unpaired UTF16 surrogate; the native crawler string API cannot represent this value"))
}

pub fn crawl(html: &str, base: &str, profile: CrawlProfile) -> Result<CrawlResult, CrawlError> {
    crawl_with_limits(html, base, profile, CrawlLimits::default())
}

pub fn crawl_with_limits(
    html: &str,
    base: &str,
    profile: CrawlProfile,
    limits: CrawlLimits,
) -> Result<CrawlResult, CrawlError> {
    if html.len() > limits.html_bytes || base.len() > limits.result_bytes {
        return Err(error(
            CrawlErrorKind::Limit,
            "HTML crawler input exceeds configured byte limit",
        ));
    }
    let chars: Vec<char> = html.chars().collect();
    let mut base = base.to_owned();
    let mut result = CrawlResult::default();
    let mut bytes: usize = 0;
    let mut count = 0;
    let mut push = |target: &mut Vec<String>, value: String| -> Result<(), CrawlError> {
        bytes = bytes
            .checked_add(value.len())
            .ok_or_else(|| error(CrawlErrorKind::Limit, "Crawler result size overflow"))?;
        count += 1;
        if bytes > limits.result_bytes || count > limits.results {
            return Err(error(
                CrawlErrorKind::Limit,
                "HTML crawler results exceed configured limits",
            ));
        }
        target.push(value);
        Ok(())
    };
    let mut i = 0;
    'main: while i < chars.len() {
        if chars[i] == '<' {
            if chars.get(i + 1) == Some(&'!') {
                i += 2;
                if starts(&chars, i, "DOCTYPE", true) {
                    i += 7;
                    while i < chars.len() {
                        let c = chars[i];
                        i += 1;
                        if c == '>' {
                            continue 'main;
                        }
                    }
                }
                for (open, close) in [("[CDATA[", "]]>"), ("--", "-->")] {
                    if starts(&chars, i, open, false) {
                        i += open.len();
                        while i < chars.len() {
                            if starts(&chars, i, close, false) {
                                i += close.len();
                                continue 'main;
                            }
                            i += 1;
                        }
                    }
                }
            }
            i += 1;
            let start = i;
            if chars.get(start).is_some_and(char::is_ascii_alphabetic) {
                while chars.get(i).is_some_and(char::is_ascii_alphanumeric) {
                    i += 1;
                }
                let tag = slice(&chars, start, i).to_ascii_uppercase();
                let mut attributes = BTreeMap::new();
                if tag == "SCRIPT" || tag == "STYLE" {
                    while i < chars.len() {
                        if starts(&chars, i, "</", false) && starts(&chars, i + 2, &tag, true) {
                            continue 'main;
                        }
                        i += 1;
                    }
                }
                while i < chars.len() {
                    let start = i;
                    if chars[i] == '>' {
                        break;
                    }
                    if attribute_name(chars[i]) {
                        i += 1;
                        while chars.get(i).is_some_and(|c| attribute_name(*c)) {
                            i += 1;
                        }
                        let name = slice(&chars, start, i).to_lowercase();
                        while chars.get(i).is_some_and(|c| whitespace(*c)) {
                            i += 1;
                        }
                        if chars.get(i) == Some(&'=') {
                            i += 1;
                            while chars.get(i).is_some_and(|c| whitespace(*c)) {
                                i += 1;
                            }
                            let value;
                            if matches!(chars.get(i), Some('\'' | '"')) {
                                let quote = chars[i];
                                i += 1;
                                let start = i;
                                let mut escaped = false;
                                while i < chars.len() {
                                    if escaped {
                                        escaped = false;
                                    } else {
                                        if chars[i] == quote {
                                            break;
                                        }
                                        if chars[i] == '\\' {
                                            escaped = true;
                                        }
                                    }
                                    i += 1;
                                }
                                value = slice(&chars, start, i);
                            } else {
                                let start = i;
                                while chars.get(i).is_some_and(|c| *c != '>' && !whitespace(*c)) {
                                    i += 1;
                                }
                                if i == chars.len() && profile == CrawlProfile::Kit2_69_2 {
                                    return Err(error(
                                        CrawlErrorKind::UpstreamNonTermination,
                                        format!(
                                            "Kit 2.69.2 loops indefinitely at unquoted attribute EOF (UTF8 byte {}); bounded native crawl stopped",
                                            slice(&chars, 0, start).len()
                                        ),
                                    ));
                                }
                                value = slice(&chars, start, i);
                                i -= 1;
                            }
                            let value = decode_entities(&value, profile)?;
                            if name != "__proto__" {
                                attributes.insert(name, value);
                            }
                        } else {
                            i -= 1;
                        }
                    }
                    i += 1;
                }
                let get = |key: &str| {
                    attributes
                        .get(key)
                        .map(String::as_str)
                        .filter(|v| !v.is_empty())
                };
                if let Some(href) = get("href") {
                    if tag == "BASE" {
                        match resolve_link(&base, href, profile) {
                            Ok(value) => {
                                if value.len() > limits.result_bytes {
                                    return Err(error(
                                        CrawlErrorKind::Limit,
                                        "Resolved HTML base exceeds configured byte limit",
                                    ));
                                }
                                base = value;
                            }
                            Err(_) => push(&mut result.invalid, href.to_owned())?,
                        }
                    } else if !get("rel").is_some_and(external) {
                        match resolve_link(&base, href, profile) {
                            Ok(v) => push(&mut result.hrefs, v)?,
                            Err(_) => push(&mut result.invalid, href.to_owned())?,
                        }
                    }
                }
                if let Some(id) = get("id") {
                    push(&mut result.ids, decode_uri(id)?)?;
                }
                if tag == "A" {
                    if let Some(name) = get("name") {
                        push(&mut result.ids, decode_uri(name)?)?;
                    }
                }
                let mut links = Vec::new();
                if let Some(src) = get("src") {
                    links.push(src.to_owned());
                }
                if let Some(srcset) = get("srcset") {
                    links.extend(source_set(srcset));
                }
                if tag == "META" {
                    if let Some(content) = get("content") {
                        if attributes
                            .get("name")
                            .or_else(|| attributes.get("property"))
                            .is_some_and(|v| meta(v))
                        {
                            links.push(content.to_owned());
                        }
                    }
                }
                for link in links {
                    match resolve_link(&base, &link, profile) {
                        Ok(v) => push(&mut result.hrefs, v)?,
                        Err(_) => push(&mut result.invalid, link)?,
                    }
                }
            }
        }
        i += 1;
    }
    Ok(result)
}

fn source_set(value: &str) -> Vec<String> {
    // Use UTF16 here because upstream resets i=0 then the for-loop increments
    // to 1 after each comma; that skipped code unit is an observable quirk.
    let storage: Vec<u16> = value.trim_matches(whitespace).encode_utf16().collect();
    let mut value = storage.as_slice();
    let ws = |c: u16| char::from_u32(c as u32).is_some_and(whitespace);
    let mut candidates = Vec::new();
    let mut inside_url = true;
    let mut i = 0;
    while i < value.len() {
        if value[i] == b',' as u16 && (!inside_url || value.get(i + 1).is_some_and(|c| ws(*c))) {
            candidates.push(&value[..i]);
            value = &value[i + 1..];
            let start = value.iter().position(|c| !ws(*c)).unwrap_or(value.len());
            let end = value.iter().rposition(|c| !ws(*c)).map_or(start, |i| i + 1);
            value = &value[start..end];
            i = 0;
            inside_url = true;
        } else if ws(value[i]) {
            inside_url = false;
        }
        i += 1;
    }
    candidates.push(value);
    candidates
        .into_iter()
        .filter_map(|candidate| {
            let end = candidate
                .iter()
                .position(|c| ws(*c))
                .unwrap_or(candidate.len());
            if end == 0 {
                None
            } else {
                Some(
                    String::from_utf16(&candidate[..end])
                        .expect("splits only on ASCII comma or BMP whitespace"),
                )
            }
        })
        .collect()
}

